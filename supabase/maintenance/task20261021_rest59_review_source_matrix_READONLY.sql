cohort AS (
 SELECT q.id,q.status::text AS status,q.format::text AS format,
        k.payload,count(o.id) AS nopts,
        count(o.id) FILTER(WHERE o.id::text=k.payload->>'correct_option_id') AS key_hits
 FROM expected e JOIN public.questions q
 ON split_part(q.source_reference,';',1)=e.source_alias AND q.status::text='review'
 LEFT JOIN public.question_keys k ON k.question_id=q.id
 LEFT JOIN public.question_options o ON o.question_id=q.id
 GROUP BY q.id,q.status,q.format,k.payload
)
SELECT count(*) AS total_found,
       count(*) FILTER(WHERE status<>'review') AS changed_review_status,
       count(*) FILTER(WHERE format<>'Y1') AS format_changed,
       count(*) FILTER(WHERE payload IS NULL OR nopts<>4 OR key_hits<>1) AS invalid_y1_key_structure
FROM cohort;

