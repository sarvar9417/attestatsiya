### Qobiliyat, ko‘nikma va kompetensiyani farqlash

**Qobiliyat** — muayyan faoliyatni samarali bajarishga yordam beradigan individual-psixologik imkoniyat. **Ko‘nikma** — mashq va tajriba jarayonida shakllanadigan bajarish usuli. **Kompetensiya** esa bilim, ko‘nikma, munosabat va ularni vazifada qo‘llash bilan bog‘liq kengroq kasbiy talab sifatida qo‘llanadi. Bularni sinonim qabul qilmang.

