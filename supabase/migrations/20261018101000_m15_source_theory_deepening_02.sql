### Pedagogik etika, takt, nutq va texnika

**Pedagogik etika** — pedagog kasbiy munosabatlariga qo‘yiladigan axloqiy talablar. **Pedagogik takt (nazokat)** — muayyan vaziyatda talabchanlik, hurmat va ta’sir me’yorini saqlay bilish. **Pedagogik texnika** — nutq, ohang, mimika, pantomimika, hissiy holatni boshqarish va muloqot vositalaridan o‘rinli foydalanish.

| Atama | Vaziyatdagi belgi |
|---|---|
| Pedagogik etika | O‘quvchining qadr-qimmati va maxfiyligini hurmat qiladi |
| Pedagogik takt | Tanqidni kamsitmasdan, to‘g‘ri payt va shaklda bildiradi |
| Nutq madaniyati | Aniqlik, ravonlik, mantiqiylik, mos ohang |
| Pedagogik texnika | Ovozni, mimikani, harakatni va o‘zini boshqarishni uyg‘unlashtiradi |

### Refleksiya — o‘z faoliyatini dalil asosida baholash

“Bugungi darsim muvaffaqiyatli bo‘ldimi, nima uchun?” degan savolni o‘ziga berish, dalillarni tahlil qilish va keyingi faoliyatni moslashtirish — **refleksiya**. Oddiy xotirlash emas: unda kuzatuv, baholash va keyingi harakat bor.

**Kooperativ refleksiya** atamasi manbadagi vaziyatda hamkasblarning o‘zaro kelishilgan, hamkorlikka tayanuvchi faoliyatiga nisbatan qo‘llangan. Refleksiya turlarini faqat vaziyatdagi signalga qarab ajrating; bitta “jamoaviy ish” ifodasi barcha refleksiya turlarini avtomatik aniqlamaydi.

