### Inklyuziv ta’lim — ishtirok va ta’lim olish imkoniyati

Inklyuziv ta’lim turli ehtiyoj va imkoniyatlarga ega o‘quvchilarning ta’lim va sinf hayotida mazmunli ishtirokini ta’minlashga intiladi. Uning maqsadi barcha o‘quvchiga mutlaqo bir xil topshiriqni majburan berish emas, balki adolatli ishtirok va o‘qishga imkon yaratishdir.

| Yondashuv | Amaliy mazmun |
|---|---|
| Inklyuziya | Ta’limdagi to‘siqlarni kamaytirish, sinfdagi tegishlilikni kuchaytirish |
| Differensiallash | Daraja, yordam, vaqt yoki faoliyat shaklini moslashtirish |
| Individual yondashuv | Muayyan o‘quvchining ehtiyoj va rivojlanish xususiyatini inobatga olish |
| Moslashtirilgan baholash | O‘quv maqsadini saqlagan holda dalil olishning mos yo‘lini tanlash |
| Qo‘llab-quvvatlovchi muhit | Xavfsizlik, kamsitmaslik, muloqot va hamkorlik |

### Vaziyatli amaliy qaror

O‘quvchi uzun yozma ko‘rsatmani tushunishda qiynalsa, o‘qituvchi uni bir necha qisqa qadamlarga ajratishi, ko‘rgazmali model berishi va tushunganini tekshirishi mumkin. Bu yordam **o‘rganish maqsadiga erishishni** qo‘llab-quvvatlashi kerak, shunchaki vazifani o‘quvchi o‘rniga bajarib qo‘yish emas.

### Ta’lim texnologiyasini dalil bilan tanlash

**Muammoli ta’lim** — o‘quvchi oldiga fikrlashni talab qiluvchi muammo qo‘yiladi. **Loyihaga asoslangan ta’lim** — maqsadli mahsulot yoki yechim uchun jarayon davomida rejalash, izlanish va taqdimot bajariladi. **Hamkorlikdagi ta’lim** — rollar va umumiy natija o‘zaro bog‘langan. **Interfaol usul** — o‘quvchilar faol fikr almashib, o‘zaro ta’sirda ishlaydi.

Bu texnologiyalarning hech biri barcha dars maqsadlari uchun yagona eng yaxshi yechim emas. Attestatsiya savolida **maqsad → sharoit → o‘quvchi ehtiyoji → metod → baholash dalili** ketma-ketligidan foydalaning.

### Inklyuziya va kasb standarti aloqasi

Kasbiy standartning xavfsiz rivojlantiruvchi ta’lim muhitiga doir sohasi barcha o‘quvchiga, jumladan alohida ehtiyojga ega bolalarga, kamsitmasdan ishtirok imkonini yaratishga qaratilgan. Biroq kasbiy standartdagi **mehnat vazifasi** bilan inklyuziv ta’limning **umumiy tamoyili**ni bir xil atama deb hisoblamang.

